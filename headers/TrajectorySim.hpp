#include "SRN.hpp"


/*naive algorithm for generating possible species count trajectories of a SRN, output is random, set a constant seed to make it deterministic.
An example of the output is plotted in figure 1 of the thesis report.
Note that the paths are equivalent to those generated by the Gillespie algorthm, but this method returns the species count at every sampled point in time, 
while the gillespie algortihm only reports the times and species counts for whenever a state changes.

INPUTS:
double deltaT: time step, reports the species count every deltaT units of time, starting at t = 0 
uint64_t timeStepCount: amount of time steps
uint32_t simCount: amount of paths to simulate, yes, full paths
const SRN* srn: pointer to stochastic reaction network structure to simulate paths for
const char* saveFileName: path to file to dump data in*/
void NaiveSRNTrajectorySim(double deltaT, uint64_t timeStepCount, uint32_t simCount, const SRN* srn, const char* saveFileName);


/*Gillespie algorithm for generating possible species count trajectories of a SRN, output is random, set a constant seed to make it deterministic.
Note that this only reports the times and species counts for whenever a state changes.

INPUTS:
double T: maximum length of path in the time dimension, stops generating path after reaching this time
uint32_t simCount: amount of paths to simulate, yes, full paths
const SRN* srn: pointer to stochastic reaction network structure to simulate paths for
const char* saveFileName: path to file to dump data in*/
void GillespieSRNTrajectorySim(double T, uint32_t simCount, const SRN* srn, const char* saveFileName);


/*========== statistics for the purpose of comparing it to some other model ==========*/

/*Approximation of the joint probability distribution at time t using the Gillespie algorithm

INPUTS:
const SRN* srn: pointer to stochastic reaction network structure to get joint probability distribution for
Tensor probabilities: Tensor in which joint probability distribution is set in, make sure that it has the same dimensions as the state space
double t: time to approximate joint probability distribution for
size_t sampleCount: amount of samples to take, more samples -> better approximation, 10000 should be more than enough*/
void GillespieSRNTrajectorySimGetFullDistribution(const SRN* srn, Tensor probabilities, double t, size_t sampleCount);


/*Approximation of the species count means for every species at time t using the Gillespie algorithm

INPUTS:
const SRN* srn: pointer to stochastic reaction network structure to get means for
Matrix mean: the means of every species are returned in the first column, obviously make sure it has at least M rows
double t: time to approximate means for
size_t sampleCount: amount of samples to take, more samples -> better approximation, 10000 should be more than enough*/
void GillespieSRNTrajectorySimGetPerSpeciesMean(const SRN* srn, Matrix mean, double t, size_t sampleCount);


/*Approximation of the species count standard deviations for every species at time t using the Gillespie algorithm

INPUTS:
const SRN* srn: pointer to stochastic reaction network structure to get standard deviations for
Matrix std: the standard deviations of every species are returned in the first column, obviously make sure it has at least M rows
double t: time to approximate standard deviations for
size_t sampleCount: amount of samples to take, more samples -> better approximation, 10000 should be more than enough*/
void GillespieSRNTrajectorySimGetPerSpeciesStandardDeviation(const SRN* srn, Matrix std, double t, size_t sampleCount);


/*Approximations of the joint probability distribution at multiple times using the Gillespie algorithm, dumps data in logFIle

INPUTS:
const SRN* srn: pointer to stochastic reaction network structure to get joint probability distributions for
double T: end time, maximum time to compare for
double sampleStep: time step size between comparisons, always starts at t = 0, next for t = sampleStep, then t = 2 * sampleStep, etc
size_t sampleCount: amount of samples to take, more samples -> better approximation, 10000 should be more than enough
FILE* logFile: pointer to FILE structure representing the file to dump data to*/
void GillespieSRNTrajectorySimLogFullDistribution(const SRN* srn, double T, double sampleStep, size_t sampleCount, FILE* logFile);


/*Approximation of the species count means for every species at multiple times using the Gillespie algorithm, dumps data in logFIle

INPUTS:
const SRN* srn: pointer to stochastic reaction network structure to get means for
double T: end time, maximum time to compare for
double sampleStep: time step size between comparisons, always starts at t = 0, next for t = sampleStep, then t = 2 * sampleStep, etc
size_t sampleCount: amount of samples to take, more samples -> better approximation, 10000 should be more than enough
FILE* logFile: pointer to FILE structure representing the file to dump data to*/
void GillespieSRNTrajectorySimLogPerSpeciesMean(const SRN* srn, double T, double sampleStep, size_t sampleCount, FILE* logFile);


/*Approximation of the species count standard deviations for every species at multiple times using the Gillespie algorithm, dumps data in logFIle

INPUTS:
const SRN* srn: pointer to stochastic reaction network structure to get standard deviations for
double T: end time, maximum time to compare for
double sampleStep: time step size between comparisons, always starts at t = 0, next for t = sampleStep, then t = 2 * sampleStep, etc
size_t sampleCount: amount of samples to take, more samples -> better approximation, 10000 should be more than enough
FILE* logFile: pointer to FILE structure representing the file to dump data to*/
void GillespieSRNTrajectorySimLogPerSpeciesStandardDeviation(const SRN* srn, double T, double sampleStep, size_t sampleCount, FILE* logFile);